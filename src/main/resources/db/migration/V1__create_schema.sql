-- Assembly plants
CREATE TABLE plants (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(20)  NOT NULL UNIQUE,
    name            VARCHAR(100) NOT NULL,
    city            VARCHAR(100) NOT NULL,
    country         VARCHAR(60)  NOT NULL,
    daily_capacity  INTEGER      NOT NULL CHECK (daily_capacity > 0),
    status          VARCHAR(20)  NOT NULL CHECK (status IN ('ACTIVE', 'MAINTENANCE', 'INACTIVE')),
    version         BIGINT       NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- Vehicle models that can be built
CREATE TABLE vehicle_models (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_code      VARCHAR(20)    NOT NULL UNIQUE,
    name            VARCHAR(100)   NOT NULL,
    category        VARCHAR(20)    NOT NULL
                    CHECK (category IN ('SEDAN', 'HATCHBACK', 'SUV', 'CROSSOVER', 'PICKUP_TRUCK', 'VAN')),
    powertrain      VARCHAR(20)    NOT NULL CHECK (powertrain IN ('PETROL', 'DIESEL', 'HYBRID', 'ELECTRIC')),
    launch_year     INTEGER        NOT NULL,
    base_price      NUMERIC(12, 2) NOT NULL CHECK (base_price > 0),
    active          BOOLEAN        NOT NULL DEFAULT TRUE,
    version         BIGINT         NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ    NOT NULL DEFAULT now()
);

-- Production orders: build N vehicles of a model at a plant
CREATE TABLE production_orders (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number        VARCHAR(30)  NOT NULL UNIQUE,
    plant_id            BIGINT       NOT NULL REFERENCES plants (id),
    vehicle_model_id    BIGINT       NOT NULL REFERENCES vehicle_models (id),
    quantity            INTEGER      NOT NULL CHECK (quantity > 0),
    completed_quantity  INTEGER      NOT NULL DEFAULT 0 CHECK (completed_quantity >= 0),
    status              VARCHAR(20)  NOT NULL
                        CHECK (status IN ('PLANNED', 'IN_PROGRESS', 'ON_HOLD', 'COMPLETED', 'CANCELLED')),
    priority            VARCHAR(20)  NOT NULL CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    planned_start_date  DATE         NOT NULL,
    planned_end_date    DATE         NOT NULL,
    actual_start_at     TIMESTAMPTZ,
    actual_end_at       TIMESTAMPTZ,
    notes               VARCHAR(500),
    version             BIGINT       NOT NULL DEFAULT 0,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT chk_completed_le_quantity CHECK (completed_quantity <= quantity),
    CONSTRAINT chk_planned_dates CHECK (planned_end_date >= planned_start_date)
);

CREATE INDEX idx_orders_plant  ON production_orders (plant_id);
CREATE INDEX idx_orders_model  ON production_orders (vehicle_model_id);
CREATE INDEX idx_orders_status ON production_orders (status);
